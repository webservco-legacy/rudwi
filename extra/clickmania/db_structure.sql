DROP TABLE IF EXISTS app_ticket;
CREATE TABLE app_ticket (
  t_sn VARCHAR(9) NOT NULL UNIQUE,
  t_week TINYINT(2) NOT NULL DEFAULT 0,
  t_row TINYINT(1) NOT NULL DEFAULT 0,
  t_col TINYINT(1) NOT NULL DEFAULT 0,
  t_val TINYINT(2) NOT NULL DEFAULT 0,
  t_date DATE NOT NULL DEFAULT '0000-00-00';
  PRIMARY KEY (t_sn)
) ENGINE=MyISAM DEFAULT CHARSET=utf8 COLLATE=utf8_unicode_ci;
